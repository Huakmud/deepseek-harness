/**
 * The model-facing `media_generate_image` tool: let a model that cannot draw
 * produce an image file and then continue working with it.
 *
 * The seam returns encoded bytes and never stores them, so this tool owns the
 * durable step: it commits the bytes through the attachment store and returns
 * the resulting reference, which the agent loop turns into an ordinary image
 * block. Nothing here needs an image-capable main model — the picture is drawn
 * by the configured media provider, and the conversation keeps the committed
 * reference like any other attachment.
 *
 * @module @deepseek-ai/dsh-tool-media/generate
 */

import type { Context } from '@deepseek-ai/cordis'
import { AttachmentError, AttachmentId } from '@deepseek-ai/dsh-attachment'
import type { ImageAttachmentRef, ImageMediaType } from '@deepseek-ai/dsh-attachment'
import type { ContentBlock } from '@deepseek-ai/dsh-llm'
import { defineTool } from '@deepseek-ai/dsh-tools'
import type { GenericCallView } from '@deepseek-ai/dsh-tools'
import { resolveMediaImage } from './image-input.ts'

/** The structured outcome declared by the `media_generate_image` output schema. */
export interface MediaGenerateValue {
  /** Durable reference of the committed image. */
  image: {
    attachmentId: string
    mediaType: string
    bytes: number
    width: number
    height: number
    name?: string
  }
  /** Provider route that drew the image. */
  provider: string
  /** Model that drew the image. */
  model: string
  /** The prompt exactly as submitted to the provider. */
  prompt: string
}

/** The image media types a provider may return; anything else cannot become a block. */
const SUPPORTED_IMAGE_TYPES: readonly ImageMediaType[] = ['image/png', 'image/jpeg', 'image/webp', 'image/gif']

/**
 * Build the model-facing result: an attribution line plus the image itself, so
 * a text-only main model reads the attribution and an image-capable one
 * additionally receives the committed reference.
 *
 * The image block is added unconditionally: a route that cannot accept images
 * has it projected to text by the adapter, so omitting the block here would
 * make generation invisible to image-capable routes too.
 * @param value - the validated generation outcome.
 * @returns the attribution text followed by the image block.
 */
export function mediaGenerateContent(value: MediaGenerateValue): ContentBlock[] {
  const { image } = value
  const name = image.name === undefined ? '' : ` (${image.name})`
  return [
    {
      type: 'text',
      text: `Generated by ${value.provider}/${value.model} through media_generate_image. Image ${image.attachmentId}${name}: ${image.width}x${image.height} px, ${image.bytes} bytes.`,
    },
    { type: 'image', attachment: imageRefFromGenerateValue(image) },
  ]
}

/**
 * Re-brand a validated generation outcome into the durable attachment reference
 * an image block carries.
 *
 * The schema types `mediaType` as a plain string, so this is the boundary that
 * turns it into the attachment service's closed set. A provider that reports an
 * unsupported format is a failure, not a silently mislabeled image.
 * @param image - the image metadata from the output schema.
 * @returns the branded attachment reference.
 * @throws when the declared media type is not a supported image format.
 */
export function imageRefFromGenerateValue(image: MediaGenerateValue['image']): ImageAttachmentRef {
  const mediaType = SUPPORTED_IMAGE_TYPES.find(candidate => candidate === image.mediaType)
  if (mediaType === undefined) {
    throw new Error(`the generated image declares an unsupported media type "${image.mediaType}"`)
  }
  return {
    attachmentId: AttachmentId(image.attachmentId),
    mediaType,
    bytes: image.bytes,
    width: image.width,
    height: image.height,
    ...image.name === undefined ? {} : { name: image.name },
  }
}

/**
 * Register the `media_generate_image` tool. The composing plugin owns the
 * attachment gate, so a deployment without durable storage registers nothing.
 * @param ctx - context whose `tools` registry receives the registration.
 * @param timeoutMs - cooperative tool-call budget attached as `ToolDefinition.timeoutMs`;
 *   image generation is slower than an ordinary request, so the deployment sets it.
 */
export function applyMediaGenerateTool(ctx: Context, timeoutMs: number): void {
  ctx.tools.register(defineTool({
    name: 'media_generate_image',
    description: 'Create an image from a text description using a separate image model, and add the resulting picture to the conversation. '
      + 'Use this whenever the user asks for a picture, diagram, or illustration to be made.',
    parameters: {
      prompt: {
        type: 'string',
        required: true,
        description: 'What the image must show. Describe subject, style, composition, and any text that must appear in it.',
      },
      size: {
        type: 'string',
        description: 'Requested output size as WIDTHxHEIGHT in pixels, for example "1024x1024". Omit for the provider default.',
      },
      referenceAttachmentId: {
        type: 'string',
        description: 'Attachment id of an image already in this conversation that the new picture should be based on or edit.',
      },
      referencePath: {
        type: 'string',
        description: 'Filesystem path of an existing image the new picture should be based on or edit.',
      },
    },
    output: {
      schema: {
        type: 'object',
        additionalProperties: false,
        properties: {
          image: {
            type: 'object',
            additionalProperties: false,
            required: true,
            properties: {
              attachmentId: { type: 'string', required: true },
              mediaType: { type: 'string', required: true },
              bytes: { type: 'integer', required: true },
              width: { type: 'integer', required: true },
              height: { type: 'integer', required: true },
              name: { type: 'string' },
            },
          },
          provider: { type: 'string', required: true },
          model: { type: 'string', required: true },
          prompt: { type: 'string', required: true },
        },
      },
      render: (_args, value) => mediaGenerateContent(value),
      presentationMeta: (_args, value) => ({ provider: value.provider, model: value.model }),
    },
    timeoutMs,
    // Generation writes one content-addressed attachment, which is idempotent.
    isConcurrencySafe: () => true,
    async execute(args, exec): Promise<MediaGenerateValue> {
      if (args.prompt.trim().length === 0) throw new Error('prompt must be a non-empty string')
      const attachments = ctx.get('attachments')
      if (attachments === undefined) {
        throw new Error('media_generate_image needs an attachment store to keep the generated image')
      }
      const reference = await resolveMediaImage(ctx, exec, {
        ...args.referenceAttachmentId === undefined ? {} : { attachmentId: args.referenceAttachmentId },
        ...args.referencePath === undefined ? {} : { path: args.referencePath },
      }).catch((error: unknown) => {
        // Neither reference named is the ordinary case, not a failure.
        if (args.referenceAttachmentId === undefined && args.referencePath === undefined) return undefined
        throw error
      })
      const result = await ctx.media.generate({
        prompt: args.prompt,
        ...args.size === undefined || args.size.trim().length === 0 ? {} : { size: args.size.trim() },
        ...reference === undefined
          ? {}
          : { reference: { data: reference.data, mediaType: reference.mediaType } },
      }, exec.signal)
      let ref: ImageAttachmentRef
      try {
        ref = await attachments.saveImage({
          data: result.data,
          mediaType: result.mediaType,
          name: generatedName(args.prompt, result.mediaType),
        })
      } catch (error: unknown) {
        if (!(error instanceof AttachmentError)) throw error
        throw new Error(
          `the provider returned an image this deployment cannot store: ${error.message}`,
          { cause: error },
        )
      }
      return {
        image: {
          attachmentId: ref.attachmentId,
          mediaType: ref.mediaType,
          bytes: ref.bytes,
          width: ref.width,
          height: ref.height,
          ...ref.name === undefined ? {} : { name: ref.name },
        },
        provider: result.provider,
        model: result.model,
        prompt: args.prompt,
      }
    },
    presentCall(args): GenericCallView {
      return {
        card: 'generic',
        title: `Create image: ${truncate(args.prompt, 80)}`,
        kind: 'other',
        ...args.referencePath === undefined ? {} : { locations: [{ path: args.referencePath }] },
      }
    },
  }))
}

/** A short derived filename so the committed image is identifiable in listings. */
function generatedName(prompt: string, mediaType: string): string {
  const slug = prompt
    .toLowerCase()
    .replaceAll(/[^a-z0-9]+/g, '-')
    .replaceAll(/^-+|-+$/g, '')
    .slice(0, 48)
  const extension = mediaType === 'image/jpeg' ? 'jpg' : mediaType.replace('image/', '')
  return `${slug.length > 0 ? slug : 'generated-image'}.${extension}`
}

/** Bound a prompt for a card title. */
function truncate(text: string, limit: number): string {
  const normalized = text.replaceAll(/\s+/g, ' ').trim()
  return normalized.length <= limit ? normalized : `${normalized.slice(0, limit - 1)}…`
}
